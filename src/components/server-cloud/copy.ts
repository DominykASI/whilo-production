export type ServerCloudCopyKey = keyof typeof SERVER_CLOUD_COPY;

export function scLabel(key: ServerCloudCopyKey, params?: Record<string, string | number>): string {
  const english = fill(SERVER_CLOUD_COPY[key], params);
  return tFromServer(key, english, params) ?? english;
}

function fill(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (Object.hasOwn(params, name) ? String(params[name]) : match));
}
