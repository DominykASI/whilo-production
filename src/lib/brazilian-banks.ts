/** Groups the catalogue by kind for the tab's sections: real banks first, then the rest. */
const KIND_ORDER: BrazilianBank["kind"][] = ["banco", "digital", "cooperativa", "financeira", "pagamento", "investimento", "cambio"];

export function banksByKind(): Array<{ kind: BrazilianBank["kind"]; banks: BrazilianBank[] }> {
  return KIND_ORDER.map((kind) => ({ kind, banks: BRAZILIAN_BANKS.filter((bank) => bank.kind === kind) })).filter((group) => group.banks.length > 0);
}

/** Matches a search against the name and the COMPE code, both of which a person types. */
export function matchBank(bank: BrazilianBank, query: string): boolean {
  const needle = query.trim().toLowerCase();
  if (!needle) return true;
  return bank.name.toLowerCase().includes(needle) || (bank.short?.toLowerCase().includes(needle) ?? false) || bank.compe.includes(needle);
}
