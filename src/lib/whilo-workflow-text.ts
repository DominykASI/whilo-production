export function whiloText(key: string, params?: Params): string {
  const template = key in en ? t(key as Parameters<typeof t>[0], params) : (FALLBACK[key] ?? key);
  if (!params || key in en) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export function isKnownKey(key: string): boolean {
  return key in en;
}
